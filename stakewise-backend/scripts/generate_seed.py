"""Generate 90 days of realistic mock UK bank data for the demo user "Priya".

Story: student working weekly shifts (irregular pay), rent of £520 on the 28th.
Small Sky Bet stakes in Aug-Sep, then prediction-market funding via crypto top-ups
and an e-wallet that escalates through October/November, often late at night.

Usage: python3 scripts/generate_seed.py   -> writes supabase/seed.sql and tests/fixtures.json
"""
import json
import random
import uuid
from datetime import date, datetime, timedelta, timezone
from pathlib import Path

random.seed(7)
USER = "00000000-0000-0000-0000-000000000001"
TODAY = date(2026, 11, 7)
START = TODAY - timedelta(days=90)
TARGET_BALANCE = 320.00

txs = []


def add(d: date, hour: int, minute: int, amount: float, desc: str, mcc=None):
    ts = datetime(d.year, d.month, d.day, hour, minute, tzinfo=timezone.utc)
    txs.append({
        "id": str(uuid.UUID(int=random.getrandbits(128))),
        "user_id": USER,
        "posted_at": ts.isoformat().replace("+00:00", "Z"),
        "amount": round(amount, 2),
        "description": desc,
        "mcc": mcc,
    })


d = START
while d <= TODAY:
    dow = d.weekday()  # Mon=0
    # Weekly shift pay every Friday, irregular amount
    if dow == 4:
        add(d, 9, 5, random.choice([150, 165, 182, 196, 204, 215, 228, 240]) + random.random(), "SHIFTWORKS LTD PAYROLL")
    # Monthly bills
    if d.day == 28:
        add(d, 7, 30, -520.00, "OAKWOOD LETTINGS RENT")
    if d.day == 12:
        add(d, 6, 15, -18.00, "EE LIMITED MOBILE")
    if d.day == 3:
        add(d, 6, 10, -5.99, "SPOTIFY UK")
    if d.day == 1:
        add(d, 6, 20, -21.99, "PUREGYM MANCHESTER")
    # Everyday spending
    for _ in range(random.choice([0, 1, 1, 1, 2])):
        add(d, random.randint(9, 20), random.randint(0, 59), -round(random.uniform(3.5, 16), 2),
            random.choice(["TESCO STORES 2231", "ALDI 114 MANCHESTER", "CO-OP GROUP 0412", "SAINSBURYS S/MKT"]))
    if dow < 5 and random.random() < 0.5:
        add(d, 8, random.randint(0, 50), -2.00, "TFGM BEE NETWORK BUS")
    if dow in (4, 5) and random.random() < 0.6:
        add(d, 19, random.randint(0, 59), -round(random.uniform(11, 19), 2), "JUST EAT.CO.UK")
    d += timedelta(days=1)

# One genuinely ambiguous transfer (money to family) - should become "ask the user"
add(date(2026, 10, 15), 12, 30, -40.00, "WISE INTL TRANSFER")

# Gambling - phase 1: small Sky Bet stakes on Saturdays (MCC 7995, caught by bank rules)
d = START
while d < date(2026, 10, 10):
    if d.weekday() == 5:
        add(d, 14, 40, -float([10, 15, 20, 15][d.toordinal() // 7 % 4]), "SKY BET", mcc="7995")
    d += timedelta(days=1)

# Phase 2: prediction-market funding via crypto + e-wallet (no 7995 code)
phase2 = [
    # (date, hour, amount, description)
    (date(2026, 10, 3), 15, 20, "COINBASE UK*TOPUP"),
    (date(2026, 10, 10), 21, 20, "COINBASE UK*TOPUP"),
    (date(2026, 10, 11), 23, 20, "COINBASE UK*TOPUP"),
    (date(2026, 10, 17), 20, 30, "COINBASE UK*TOPUP"),
    (date(2026, 10, 18), 0, 25, "SKRILL*PAY 8812"),
    (date(2026, 10, 24), 22, 30, "COINBASE UK*TOPUP"),
    (date(2026, 10, 25), 1, 40, "COINBASE UK*TOPUP"),
    (date(2026, 10, 30), 10, 30, "COINBASE UK*TOPUP"),
    (date(2026, 10, 31), 23, 40, "COINBASE UK*TOPUP"),
    (date(2026, 11, 1), 1, 50, "COINBASE UK*TOPUP"),
    (date(2026, 11, 1), 2, 25, "SKRILL*PAY 8812"),
    (date(2026, 11, 6), 11, 40, "COINBASE UK*TOPUP"),
    (date(2026, 11, 7), 0, 60, "COINBASE UK*TOPUP"),
]
for dt, hr, amt, desc in phase2:
    add(dt, hr, random.randint(0, 50), -float(amt), desc)

txs.sort(key=lambda t: t["posted_at"])
net = round(sum(t["amount"] for t in txs), 2)
opening = round(TARGET_BALANCE - net, 2)

root = Path(__file__).resolve().parents[1]
lines = [
    "-- Demo seed: Priya, 90 days of mock transactions. Generated by scripts/generate_seed.py",
    f"-- Opening balance {opening} -> current balance {TARGET_BALANCE}",
    "insert into public.profiles (id, first_name, language, plain_language, current_balance) values",
    f"  ('{USER}', 'Priya', 'English', true, {TARGET_BALANCE}) on conflict (id) do update set current_balance = excluded.current_balance;",
    "delete from public.transactions where user_id = '%s';" % USER,
    "insert into public.limits (user_id) values ('%s') on conflict (user_id) do nothing;" % USER,
    "insert into public.transactions (id, user_id, posted_at, amount, description, mcc) values",
]
vals = []
for t in txs:
    mcc = f"'{t['mcc']}'" if t["mcc"] else "null"
    desc = t["description"].replace("'", "''")
    vals.append(f"  ('{t['id']}', '{USER}', '{t['posted_at']}', {t['amount']}, '{desc}', {mcc})")
lines.append(",\n".join(vals) + ";")
(root / "supabase" / "seed.sql").write_text("\n".join(lines) + "\n")
(root / "tests" / "fixtures.json").write_text(json.dumps({
    "today": TODAY.isoformat(), "balance": TARGET_BALANCE, "transactions": txs}, indent=1))
print(f"{len(txs)} transactions, opening {opening}, current {TARGET_BALANCE}")
