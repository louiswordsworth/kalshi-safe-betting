"""Generate 90 days of mock UK bank data for a SECOND demo user, "Marcus".

Story: salaried, paid monthly, comfortable. He bets a little every week (a Saturday Bet365 punt and a
fortnightly crypto top-up for a prediction market), but it is steady, daytime and well within his means.
This is the contrast to Priya: the same £40 stake that is blocked for her passes for him.

Usage: python3 scripts/generate_seed_marcus.py
  -> writes supabase/seed_marcus.sql and tests/fixtures_marcus.json
To demo him, load seed_marcus.sql and set the secret DEMO_USER_ID=00000000-0000-0000-0000-000000000002
(keep DEMO_MODE=true and DEMO_TODAY=2026-11-07). Priya's seed and Marcus's seed can live in the same database.
"""
import json
import random
import uuid
from datetime import date, datetime, timedelta, timezone
from pathlib import Path

random.seed(11)
USER = "00000000-0000-0000-0000-000000000002"
TODAY = date(2026, 11, 7)
START = TODAY - timedelta(days=90)
TARGET_BALANCE = 1450.00
SALARY = 2648.37

txs = []


def add(d: date, hour: int, minute: int, amount: float, desc: str, mcc=None):
    ts = datetime(d.year, d.month, d.day, hour, minute, tzinfo=timezone.utc)
    txs.append({
        "id": str(uuid.UUID(int=random.getrandbits(128))),
        "user_id": USER,
        "posted_at": ts.isoformat().replace("+00:00", "Z"),
        "amount": round(amount, 2),
        "description": desc,
        "mcc": mcc,
    })


def payday_for(year: int, month: int) -> date:
    """Paid on the 25th, or the Friday before if that is a weekend."""
    d = date(year, month, 25)
    while d.weekday() >= 5:
        d -= timedelta(days=1)
    return d


paydays = {payday_for(y, m) for y, m in [(2026, 8), (2026, 9), (2026, 10), (2026, 11)]}

d = START
while d <= TODAY:
    dow = d.weekday()  # Mon=0
    if d in paydays:
        add(d, 6, 0, SALARY, "BRIGHTHILL CONSULTING PAYROLL")
    # Monthly bills (fixed amounts, so they are detected as recurring)
    if d.day == 1:
        add(d, 6, 30, -950.00, "HARGREAVES LETTINGS RENT")
        add(d, 6, 31, -164.00, "MANCHESTER CITY COUNCIL")
    if d.day == 2:
        add(d, 6, 10, -24.99, "PUREGYM MANCHESTER")
    if d.day == 3:
        add(d, 6, 10, -11.99, "SPOTIFY UK")
    if d.day == 5:
        add(d, 6, 15, -88.00, "OCTOPUS ENERGY DD")
    if d.day == 8:
        add(d, 6, 20, -32.00, "VIRGIN MEDIA")
    if d.day == 12:
        add(d, 6, 15, -22.00, "VODAFONE LTD")
    if d.day == 14:
        add(d, 6, 10, -10.99, "NETFLIX.COM")
    if d.day == 26:
        add(d, 7, 0, -300.00, "SAVINGS POT TRANSFER")
    # Everyday spending
    for _ in range(random.choice([0, 1, 1, 2])):
        add(d, random.randint(9, 20), random.randint(0, 59), -round(random.uniform(5, 24), 2),
            random.choice(["TESCO STORES 2231", "M&S SIMPLY FOOD 0188", "WAITROSE MANCHESTER", "ALDI 114 MANCHESTER"]))
    if dow < 5:
        add(d, 8, random.randint(0, 50), -round(random.choice([2.0, 2.0, 4.0]), 2), "TFGM BEE NETWORK BUS")
        if random.random() < 0.6:
            add(d, 12, random.randint(0, 40), -round(random.uniform(5.5, 9.5), 2), "PRET A MANGER")
    if dow in (4, 5) and random.random() < 0.7:
        add(d, 19, random.randint(0, 59), -round(random.uniform(18, 45), 2), random.choice(["DELIVEROO", "DISHOOM MANCHESTER", "THE ALBION PUB"]))
    if random.random() < 0.08:
        add(d, random.randint(10, 18), random.randint(0, 59), -round(random.uniform(15, 70), 2), "AMAZON.CO.UK")
    if random.random() < 0.05:
        add(d, random.randint(18, 23), random.randint(0, 59), -round(random.uniform(8, 22), 2), "UBER *TRIP")
    d += timedelta(days=1)

# Betting is small and steady. Saturday afternoon punts on Bet365 (MCC 7995, so the bank's own rules see them)...
bet365 = {  # Saturday: stake
    date(2026, 8, 15): 15, date(2026, 8, 22): 20, date(2026, 9, 5): 10, date(2026, 9, 12): 20,
    date(2026, 9, 19): 15, date(2026, 9, 26): 25, date(2026, 10, 10): 20, date(2026, 10, 17): 15,
    date(2026, 10, 24): 20, date(2026, 10, 31): 15,
}
for dt, amt in bet365.items():
    add(dt, 14, random.randint(10, 40), -float(amt), "BET365", mcc="7995")

# ...plus a fortnightly crypto top-up for a prediction market. Evenings, flat amounts, nowhere near payday.
# This route has no 7995 code, so BetCheck puts it to the user as "was this for betting?"
for dt, amt in [(date(2026, 9, 5), 30), (date(2026, 9, 19), 35), (date(2026, 10, 3), 40),
                (date(2026, 10, 17), 35), (date(2026, 10, 31), 30)]:
    add(dt, random.randint(17, 20), random.randint(0, 50), -float(amt), "COINBASE UK*TOPUP")

txs.sort(key=lambda t: t["posted_at"])
net = round(sum(t["amount"] for t in txs), 2)
opening = round(TARGET_BALANCE - net, 2)

root = Path(__file__).resolve().parents[1]
lines = [
    "-- Demo seed 2: Marcus, salaried and comfortable. 90 days of mock transactions. Generated by scripts/generate_seed_marcus.py",
    f"-- Opening balance {opening} -> current balance {TARGET_BALANCE}",
    "insert into public.profiles (id, first_name, language, plain_language, current_balance) values",
    f"  ('{USER}', 'Marcus', 'English', true, {TARGET_BALANCE}) on conflict (id) do update set current_balance = excluded.current_balance;",
    "delete from public.transactions where user_id = '%s';" % USER,
    "insert into public.limits (user_id) values ('%s') on conflict (user_id) do nothing;" % USER,
    "insert into public.transactions (id, user_id, posted_at, amount, description, mcc) values",
]
vals = []
for t in txs:
    mcc = f"'{t['mcc']}'" if t["mcc"] else "null"
    desc = t["description"].replace("'", "''")
    vals.append(f"  ('{t['id']}', '{USER}', '{t['posted_at']}', {t['amount']}, '{desc}', {mcc})")
lines.append(",\n".join(vals) + ";")
(root / "supabase" / "seed_marcus.sql").write_text("\n".join(lines) + "\n")
(root / "tests" / "fixtures_marcus.json").write_text(json.dumps({
    "today": TODAY.isoformat(), "balance": TARGET_BALANCE, "transactions": txs}, indent=1))
print(f"{len(txs)} transactions, opening {opening}, current {TARGET_BALANCE}")
